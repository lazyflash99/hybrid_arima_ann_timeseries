"""Writes RESULTS_SUMMARY.md from the CSV files in results/.
Usage:  python make_results_summary.py"""
import os

import pandas as pd

from config import ROOT, results_path


def md(df):
    cols = list(df.columns)
    rows = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        rows.append("| " + " | ".join("n/a" if isinstance(v, float) and v != v else f"{v:.4g}" if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(rows)


def main():
    out = ["# Results summary", "", "Generated by `make_results_summary.py` from the CSV files in `results/`.", ""]
    v = pd.read_csv(results_path("validation_results.csv"))
    ok = v[(v.status == "ok") & (v.window == "all test points")]
    for protocol, title in (("fixed", "Fixed split (Zhang's protocol)"), ("rolling", "Rolling origin with validation-only tuning")):
        t = ok[ok.protocol == protocol].groupby(["dataset", "model"], sort=False)["MSE"].mean().unstack("model")
        shown = t.astype(object)
        for r in v[(v.status != "ok") & (v.protocol == protocol)].itertuples():
            if r.dataset in shown.index and r.model in shown.columns:
                shown.loc[r.dataset, r.model] = f"n/a ({r.status})"
        out += [f"## {title}: mean test MSE, one step ahead, over all test points", "", md(shown.reset_index()), ""]
        wins = []
        for name, row in t.iterrows():
            if "Zhang" in row and "ARIMA" in row:
                best = row.dropna().idxmin()
                wins.append(dict(dataset=name, best_model=best, Zhang_beats_ARIMA=bool(row["Zhang"] < row["ARIMA"]),
                                 Extension_beats_Zhang=bool(row["Extension"] < row["Zhang"]) if "Extension" in row else None))
        out += [md(pd.DataFrame(wins)), ""]
    dm = pd.read_csv(results_path("validation_dm.csv"))
    d = dm[(dm.versus == "Zhang") & (dm.model == "Extension")][["protocol", "dataset", "dm_stat", "p_value"]]
    out += ["## Diebold-Mariano: Extension against Zhang (positive = Extension has the lower loss)", "", md(d), "",
            f"Significant at 5%: {int((d.p_value < 0.05).sum())} of {len(d)}.", ""]
    mcs = pd.read_csv(results_path("validation_mcs.csv"))
    sets = mcs[mcs.in_90pct_set].groupby(["protocol", "dataset"])["model"].apply(lambda s: ", ".join(s)).reset_index(name="models in the 90% confidence set")
    out += ["## Model confidence set", "", md(sets), ""]
    if os.path.exists(results_path("nonlinearity_vs_improvement.csv")):
        out += ["## Nonlinearity in ARIMA residuals against hybrid improvement", "", md(pd.read_csv(results_path("nonlinearity_vs_improvement.csv"))), ""]
    if os.path.exists(results_path("grid_when.csv")):
        out += ["## Which hybrid works when", "", md(pd.read_csv(results_path("grid_when.csv"))), "",
                "seasonal_strength is n/a for data sets without a seasonal period. The grid has no GRU + joint-input design: "
                "n/a (that combiner needs a network that takes the joint inputs, which the GRU here does not).", ""]
    with open(os.path.join(ROOT, "RESULTS_SUMMARY.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote RESULTS_SUMMARY.md")


if __name__ == "__main__":
    main()
